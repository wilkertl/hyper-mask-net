"""The drafted G2 decision and its proposed ADR, from the same result files as the E1 report.

The outcome is computed from research R8's two criteria only; fit, the global-selector payoff,
and the fixed-subset comparisons are context. The researcher decides in the ADR.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from hyperdime.contracts.schemas import Criterion, GateDecision
from hyperdime.evaluation.transfer import ALPHA
from hyperdime.reports.e0 import _fmt
from hyperdime.reports.e1 import (
    NOTES,
    E1Results,
    criteria,
    departures,
    fixed_subset_rows,
    payoff,
)

TAG = "g2-selector-shift"
DEFAULT_ADR = Path("docs/decisions/ADR-0007-g2-selector-shift.md")
_STATUS = re.compile(r"^- \*\*Status:\*\* (\w+)", re.MULTILINE)


def decision(e1: E1Results, adr: Path) -> GateDecision:
    computed = criteria(e1)
    fit = ", ".join(
        f"{env} {'fits' if row['fits'] else 'does not fit'} (gain {_fmt(row['mean_gain'], '+')},"
        f" Holm p {_fmt(row['p_holm'])})"
        for env, row in sorted(e1.fit.items())
    )
    context = {
        "fit": fit,
        "payoff": _significant(payoff(e1), "above the global selector"),
        "fixed_subset": _significant(fixed_subset_rows(e1), "above a fixed subset"),
        **{f"note_{env}": NOTES[env] for env in e1.environments if env in NOTES},
        **{f"departure_{i}": line for i, line in enumerate(departures(e1))},
    }
    return GateDecision(
        gate="G2",
        outcome="pass" if all(c["met"] for c in computed) else "fail",
        criteria=[
            Criterion(name=c["name"], value=c["value"], threshold=c["threshold"], met=c["met"])
            for c in computed
        ],
        context=context,
        evidence=[e1.run, *e1.seeded_runs],
        adr=adr.as_posix(),
        tag=TAG,
    )


def proposed_adr(e1: E1Results, record: GateDecision) -> str:
    computed = criteria(e1)
    reading = "pass" if record.outcome == "pass" else "fail"
    lines = [
        "# ADR-0007: Gate G2 — selector shift (H1)",
        "",
        "- **Status:** proposed",
        f"- **Date:** {e1.finished}",
        "- **Issue:** #20, F4 (`specs/005-selector-shift`), experiment E1",
        "",
        "## Context",
        "",
        "G2 asks whether selectors trained on different environments select different dimensions",
        "beyond seed-to-seed variation, and whether that costs retrieval when a selector is moved",
        "(research R8). If not, the hypernetwork is not needed. This draft is generated by",
        "`hyperdime decide G2` from the result files of `reports/E1/README.md`.",
        "",
        "## Evidence",
        "",
        f"From transfer-matrix `{e1.run}` (commit `{e1.commit[:12]}`); every value is in",
        "`reports/E1/README.md`.",
        "",
        *[
            f"- **Criterion {c['name']}**: {c['shown']}; threshold {c['threshold']}; "
            f"{'met' if c['met'] else 'not met'}."
            for c in computed
        ],  # fmt: skip
        "",
        "Context, not decisive:",
        "",
        *[f"- **{key}**: {value}" for key, value in sorted(record.context.items())],
        "",
        "## Decision",
        "",
        f"Research R8's criteria read **{reading}**. The decision is the researcher's: accept this",
        "reading, or amend it here with the reasons.",
        "",
        "## Consequences",
        "",
        f"- On acceptance, the merge of this ADR is tagged `{TAG}`.",
        "- If G2 passes: F5 (space descriptor) may be specified.",
        "- If G2 fails: Milestone 3 and 4 issues close as not planned, and an issue is opened",
        "  for a universal selector (issue #20).",
    ]
    return "\n".join(lines) + "\n"


def write_adr(e1: E1Results, record: GateDecision, path: Path) -> Path:
    """Write the proposed ADR; an existing ADR is overwritten only while it is still proposed."""
    if path.exists():
        found = _STATUS.search(path.read_text(encoding="utf-8"))
        if found is None or found.group(1) != "proposed":
            raise ValueError(f"{path} is no longer proposed; it is not overwritten")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(proposed_adr(e1, record), encoding="utf-8")
    return path


def _significant(rows: list[dict[str, Any]], what: str) -> str:
    hits = [r for r in rows if r["diff"] > 0 and r["p_holm"] <= ALPHA]
    return f"in-domain selector significantly {what} in {len(hits)} of {len(rows)} comparisons"

"""Generated P3-bench reports (F12; ADR-0018; specs/013 FR-007, FR-009, FR-011-FR-013, US1/AC4).

Everything here is computed from run files: summaries, manifests, selection records, the
resource record, and the probe. Nothing here reads a judgment, so regenerating a report never
reads evaluation labels again. The text is a pure function of its inputs, so a regenerated report
is byte-identical (SC-004).
"""


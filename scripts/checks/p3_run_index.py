"""List every P3 run under an artifact root, with its purpose, from manifests and summaries.

    python scripts/checks/p3_run_index.py artifacts reports/P3/RUNS.md --label <run_id>=canonical

Costs and coverage come from each run's own files; only the purpose comes from ``--label``, and a
run without a label is listed as not reviewed. So a pilot or a failed start cannot pass for the
canonical run. Exact run ids, no query or document ids.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from hyperdime.contracts.manifests import read_manifest

COLUMNS = (
    "run", "purpose", "environment", "device", "commit", "dirty", "batch pairs", "queries", "pairs",
    "multi-positive", "total s", "read s", "transfer s", "compute s", "write s", "plan s",
    "peak allocated MiB", "peak reserved MiB", "peak RSS MiB",
)  # fmt: skip


def _rows(run: Path, purpose: str) -> list[list[str]]:
    manifest = read_manifest(run)
    rows = []
    for path in sorted(run.glob("*/summary.json")):
        summary = json.loads(path.read_text(encoding="utf-8"))
        curves = json.loads((path.parent / "curves.json").read_text(encoding="utf-8"))
        cost = summary["cost"]
        phase = cost.get("phase_seconds", {})
        memory = cost.get("device_memory", {})
        rows.append([
            f"`{run.name}`", purpose, path.parent.name, cost.get("device", manifest.device),
            manifest.git_commit[:12], str(manifest.git_dirty), str(cost.get("batch_pairs", "")),
            str(curves["coverage"]["queries"]), str(summary["identities"]["pairs"]),
            str(curves["coverage"]["multi_positive_queries"]), f"{cost['total_seconds']:.1f}",
            *[f"{phase.get(name, 0.0):.1f}" for name in ("read", "transfer", "compute", "write",
                                                         "plan")],
            f"{memory.get('peak_allocated_mib', 0.0):.0f}",
            f"{memory.get('peak_reserved_mib', 0.0):.0f}", f"{cost['peak_rss_mib']:.0f}",
        ])  # fmt: skip
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("root", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--label", action="append", default=[], metavar="RUN=PURPOSE")
    args = parser.parse_args(argv)
    labels = dict(item.split("=", 1) for item in args.label)
    runs = sorted(p for p in (args.root / "evaluation" / "P3" / "all").iterdir() if p.is_dir())
    lines = [
        "# P3 runs",
        "",
        "Generated by `scripts/checks/p3_run_index.py`. Only the `canonical` run is reported.",
        "`read`, `transfer`, `compute`, `write`, and `plan` are the batched kernels only, a part",
        "of `total`. Peak RSS is the process peak so far and counts pages of memory-mapped files.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    for run in runs:
        for row in _rows(run, labels.get(run.name, "not reviewed")):
            lines.append("| " + " | ".join(row) + " |")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())

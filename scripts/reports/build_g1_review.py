"""Build the G1 review page (HTML) from the generated E0 tables and the official selector files.

Every number on the page is read from ``reports/E0/tables/*.csv`` (generated by
``hyperdime report E0`` from result files) or from the official ``selection.json`` of each
environment (copied from ``artifacts/selectors/official/<env>/<run>/``). Prose carries no numbers.

    python scripts/reports/build_g1_review.py --tables reports/E0/tables \\
        --selections <dir with scifact.json nfcorpus.json msmarco.json> --out g1-review.html
"""
# The HTML template below is prose and markup; it is exempt from line length.
# ruff: noqa: E501

from __future__ import annotations

import argparse
import csv
import html
import json
from pathlib import Path

LINES = (
    ("prefix", "Prefix (first k)"),
    ("random", "Random k"),
    ("l2s", "L2S selector"),
    ("oracle", "Oracle"),
)
SETS = (
    ("trec-dl-2019", "TREC DL 2019"),
    ("trec-dl-2020", "TREC DL 2020"),
    ("trec-dl-hard", "DL-HARD"),
)
METHOD_NAMES = {
    "full": "Full 1024",
    "prefix": "Prefix",
    "random": "Random",
    "global-importance": "Global importance",
    "l2s": "L2S (official)",
    "selected": "Selected candidate",
    "oracle": "Oracle",
}
ENV_NAMES = {"scifact": "SciFact", "nfcorpus": "NFCorpus", "msmarco": "MS MARCO dev"}


def read(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def esc(text: object) -> str:
    return html.escape(str(text))


def criteria_section(rows: list[dict[str, str]]) -> str:
    items = []
    for row in rows:
        met = row["met"] == "yes"
        letter, _, text = row["criterion"].partition(") ")
        items.append(
            f'<li class="criterion {"ok" if met else "bad"}">'
            f'<span class="pill">{"✓ met" if met else "✕ not met"}</span>'
            f'<div><p class="ctext"><b>{esc(letter)})</b> {esc(text)}</p>'
            f'<p class="cval">{esc(row["value"])}</p></div></li>'
        )
    passed = sum(r["met"] == "yes" for r in rows)
    return f'<ul class="criteria">{"".join(items)}</ul>', passed, len(rows)


def headline_table(rows: list[dict[str, str]]) -> str:
    methods = [m for m in METHOD_NAMES if m in rows[0]]
    head = "".join(f"<th>{esc(METHOD_NAMES[m])}</th>" for m in methods)
    body = []
    for row in rows:
        full = float(row["full"])
        cells = []
        for m in methods:
            value = float(row[m])
            delta = (
                ""
                if m == "full"
                else f'<span class="delta {"up" if value > full else "down"}">{value - full:+.3f}</span>'
            )
            cells.append(f"<td><span class='num'>{value:.4f}</span>{delta}</td>")
        body.append(
            f'<tr><th scope="row">{esc(ENV_NAMES.get(row["environment"], row["environment"]))}</th>{"".join(cells)}</tr>'
        )
    return f'<div class="tablewrap"><table class="data"><thead><tr><th>Test set</th>{head}</tr></thead><tbody>{"".join(body)}</tbody></table></div>'


def significance_table(rows: list[dict[str, str]]) -> str:
    body = []
    for row in rows:
        p = float(row["p_holm"])
        sig = p < 0.05
        body.append(
            f'<tr class="{"sig" if sig else ""}"><td>{esc(ENV_NAMES.get(row["environment"], row["environment"]))}</td>'
            f"<td>{esc(METHOD_NAMES.get(row['method'], row['method']))}</td><td>{esc(METHOD_NAMES.get(row['against'], row['against']))}</td>"
            f'<td class="num">{esc(row["diff"])}</td><td class="num">[{esc(row["ci_low"])}, {esc(row["ci_high"])}]</td>'
            f'<td class="num">{esc(row["p_holm"])}</td><td>{"yes" if sig else "no"}</td></tr>'
        )
    return (
        '<div class="tablewrap"><table class="data"><thead><tr><th>Environment</th><th>Method</th><th>Against</th>'
        "<th>Δ nDCG@10</th><th>95% CI</th><th>p (Holm)</th><th>Significant</th></tr></thead>"
        f"<tbody>{''.join(body)}</tbody></table></div>"
    )


def chart(rows: list[dict[str, str]], title: str, lo: float, hi: float) -> str:
    """One small multiple: nDCG@10 by budget; full 1024 as a dashed reference line."""
    budgets = [int(c.split("=")[1]) for c in rows[0] if c.startswith("k=")]
    by = {r["method"]: [float(r[f"k={k}"]) for k in budgets] for r in rows}
    w, h, left, right, top, bottom = 360, 250, 44, 96, 14, 34
    x = lambda k: left + (k - budgets[0]) / (budgets[-1] - budgets[0]) * (w - left - right)  # noqa: E731
    y = lambda v: top + (hi - v) / (hi - lo) * (h - top - bottom)  # noqa: E731
    parts = [
        f'<svg viewBox="0 0 {w} {h}" role="img" aria-label="{esc(title)}: nDCG@10 by number of kept dimensions">'
    ]
    ticks = [round(lo + i * (hi - lo) / 4, 2) for i in range(5)]
    for t in ticks:
        parts.append(
            f'<line class="grid" x1="{left}" x2="{w - right}" y1="{y(t):.1f}" y2="{y(t):.1f}"/>'
        )
        parts.append(
            f'<text class="tick" x="{left - 6}" y="{y(t) + 3.5:.1f}" text-anchor="end">{t:.2f}</text>'
        )
    for k in (102, 307, 512, 716, 1024):
        parts.append(
            f'<text class="tick" x="{x(k):.1f}" y="{h - bottom + 16}" text-anchor="middle">{k}</text>'
        )
    parts.append(
        f'<text class="axis" x="{(left + w - right) / 2:.1f}" y="{h - 3}" text-anchor="middle">dimensions kept (k of 1024)</text>'
    )
    full = by["full"][0]
    parts.append(
        f'<line class="ref" x1="{left}" x2="{w - right}" y1="{y(full):.1f}" y2="{y(full):.1f}"><title>Full 1024: {full:.4f}</title></line>'
    )
    labels = []
    for slot, (method, name) in enumerate(LINES, start=1):
        values = by[method]
        points = " ".join(f"{x(k):.1f},{y(v):.1f}" for k, v in zip(budgets, values, strict=True))
        parts.append(f'<polyline class="line s{slot}" points="{points}"/>')
        for k, v in zip(budgets, values, strict=True):
            parts.append(
                f'<circle class="dot s{slot}" cx="{x(k):.1f}" cy="{y(v):.1f}" r="4">'
                f"<title>{esc(name)} · k = {k} · nDCG@10 {v:.4f}</title></circle>"
            )
        labels.append([y(values[-2]), name, slot])
    labels.append([y(full), "Full 1024", 0])
    labels.sort()
    for i in range(1, len(labels)):
        labels[i][0] = max(labels[i][0], labels[i - 1][0] + 12)
    for ly, name, slot in labels:
        cls = "lab ref-lab" if slot == 0 else "lab"
        parts.append(f'<text class="{cls}" x="{w - right + 8}" y="{ly + 4:.1f}">{esc(name)}</text>')
    parts.append("</svg>")
    return f'<figure class="panel"><figcaption>{esc(title)}</figcaption>{"".join(parts)}</figure>'


def fit_table(selection: dict) -> str:
    """NFCorpus: validation KL of each official cell against the uniform predictor."""
    cells = sorted(
        selection["cells"].values(), key=lambda c: (c["cell"]["temperature"], c["cell"]["epochs"])
    )
    body = []
    for c in cells:
        ratio = c["val_kl"] / c["uniform_kl"]
        chosen = c is selection["cells"][selection["chosen"]]
        body.append(
            f'<tr class="{"chosen" if chosen else ""}"><td class="num">{c["cell"]["temperature"]:g}</td>'
            f'<td class="num">{c["cell"]["epochs"]}</td><td class="num">{c["val_kl"]:.2e}</td>'
            f'<td class="num">{c["uniform_kl"]:.2e}</td>'
            f'<td class="num {"good" if ratio < 1 else "badtxt"}">{ratio:.3f}</td>'
            f'<td class="num">{c["validation_ndcg@10"]:.4f}</td><td>{"chosen" if chosen else ""}</td></tr>'
        )
    return (
        '<div class="tablewrap"><table class="data compact"><thead><tr><th>τ</th><th>Epochs</th>'
        "<th>Selector KL</th><th>Uniform KL</th><th>Ratio (&lt; 1 beats uniform)</th>"
        f"<th>Validation nDCG@10</th><th></th></tr></thead><tbody>{''.join(body)}</tbody></table></div>"
    )


def selection_table(rows: list[dict[str, str]]) -> str:
    body = "".join(
        f'<tr><td>{esc(ENV_NAMES.get(r["environment"], r["environment"]))}</td><td class="mono">{esc(r["official cell"])}</td>'
        f'<td class="num">{esc(r["official validation nDCG@10"])}</td><td>{esc(r["selected"])}</td>'
        f'<td class="mono small">{esc(r["family scores"])}</td></tr>'
        for r in rows
    )
    return (
        '<div class="tablewrap"><table class="data"><thead><tr><th>Environment</th><th>Official cell</th>'
        "<th>Validation nDCG@10</th><th>Selected</th><th>Best validation score per family</th></tr></thead>"
        f"<tbody>{body}</tbody></table></div>"
    )


def build(tables: Path, selections: Path) -> str:
    g1 = read(tables / "g1.csv")
    criteria, passed, total = criteria_section(g1)
    headline = read(tables / "l2s_style.csv")
    dime = {name: read(tables / f"dime_{name}_ndcg10.csv") for name, _ in SETS}
    values = [
        float(r[c])
        for rows in dime.values()
        for r in rows
        for c in r
        if c.startswith("k=") and r["method"] in {"full", *(m for m, _ in LINES)}
    ]
    lo, hi = (int(min(values) * 10)) / 10, (int(max(values) * 10) + 1) / 10
    panels = "".join(chart(dime[name], title, lo, hi) for name, title in SETS)
    nf = json.loads((selections / "nfcorpus.json").read_text(encoding="utf-8"))
    runs = "".join(
        f"<li><b>{esc(ENV_NAMES.get(r['environment'], r['environment']))}</b> evaluation <code>{esc(r['run'])}</code></li>"
        for r in headline
    )
    legend = "".join(
        f'<span class="key"><i class="sw s{i}"></i>{esc(n)}</span>'
        for i, (_, n) in enumerate(LINES, 1)
    )
    return TEMPLATE.format(
        criteria=criteria,
        passed=passed,
        total=total,
        headline=headline_table(headline),
        panels=panels,
        legend=legend,
        significance=significance_table(read(tables / "significance.csv")),
        fit=fit_table(nf),
        selection=selection_table(read(tables / "selection.csv")),
        runs=runs,
    )


